#!/usr/bin/env python3
"""Check that every figure the deck shows on slides 4-7 traces back to the raw files.

Recomputes from the raw evidence, without using any summary file:
  * per-run p50, sample count and errors from each .jtl                 vs results/a2/speed/<config>.json
  * pooled p95 from all three .jtl files                                vs results/a2/speed/summary.json
  * escalation per run from results/logs/a2_requests.jsonl              vs results/a2/speed/<config>.json
  * cascade test-set accuracy from <config>_test_predictions.csv + golden set
  * GET /stats increase vs 200 lines in the service log, per run
and checks the built deck has no PENDING box or DRAFT banner left.

    python3 tools/a2_crosscheck.py      -> results/a2/crosscheck.md   (exit 1 on any mismatch)
"""
from __future__ import annotations

import csv
import os
import sys
from pathlib import Path

from a2_common import A2, A2_LOG, ROOT, golden, iter_log, jload, pct, read_csv, split_rows
from a2_analyze_speed import UNFINISHED_MARKERS

TOL = 0.05   # seconds / fraction


def jtl_rows(path):
    with open(path, newline="", encoding="utf-8", errors="replace") as fh:
        return [r for r in csv.DictReader(fh) if "POST /tickets" in r.get("label", "")]


def main() -> int:
    lines = ["# Raw-file cross-check (generated by `tools/a2_crosscheck.py`)", "",
             "| Check | Raw files | Summary used by the deck | Match |", "|---|---|---|---|"]
    bad = 0

    def chk(name, raw, used, ok):
        nonlocal bad
        bad += not ok
        lines.append(f"| {name} | {raw} | {used} | {'yes' if ok else '**NO**'} |")

    log = {}
    for r in iter_log(A2_LOG):
        if r.get("endpoint") == "POST /tickets":
            log.setdefault(r.get("run_id"), []).append(r)

    speed = jload(A2 / "speed" / "summary.json") or {}
    for cfg in speed:
        js = jload(A2 / "speed" / f"{cfg}.json")
        pooled = []
        for run in js["runs"]:
            tag = run["tag"]
            rows = jtl_rows(A2 / "jtl" / f"{tag}.jtl")
            ok_lat = [float(r["elapsed"]) / 1000 for r in rows if r.get("success", "").lower() == "true"]
            pooled += ok_lat
            p50 = pct(ok_lat, 50)
            chk(f"{tag} p50 (s)", f"{p50:.2f}", f"{run['p50_s']:.2f}", abs(p50 - run["p50_s"]) <= TOL)
            failed = [r for r in rows if r.get("success", "").lower() != "true"]
            cut = [r for r in failed if any(m in f"{r.get('responseCode', '')} {r.get('responseMessage', '')}" for m in UNFINISHED_MARKERS)]
            chk(f"{tag} samples / errored / timed out", f"{len(rows)} / {len(failed) - len(cut)} / {len(cut)}",
                f"{run['jtl_samples']} / {run['errored']} / {run.get('timed_out', 0)}",
                len(rows) == run["jtl_samples"] and len(failed) - len(cut) == run["errored"] and len(cut) == run.get("timed_out", 0))
            L = [x for x in log.get(tag, []) if x.get("status") == 200]
            if cfg != "top7b":
                e = sum(bool(x.get("escalated")) for x in L) / len(L) if L else None
                chk(f"{tag} escalation", "–" if e is None else f"{e:.3f}", "–" if run["escalation_fraction"] is None else f"{run['escalation_fraction']:.3f}",
                    e is not None and run["escalation_fraction"] is not None and abs(e - run["escalation_fraction"]) <= 1e-9)
            b, a = jload(A2 / "runs" / f"{tag}.stats_before.json"), jload(A2 / "runs" / f"{tag}.stats_after.json")
            if a and b:
                chk(f"{tag} GET /stats increase vs log 200s", a["total"] - b["total"], len(L), a["total"] - b["total"] == len(L))
        p95 = pct(pooled, 95)
        chk(f"{cfg} pooled p95 (s)", f"{p95:.2f} (n={len(pooled)})", f"{speed[cfg]['p95_pooled_s']:.2f} (n={speed[cfg]['p95_pooled_n']})",
            abs(p95 - speed[cfg]["p95_pooled_s"]) <= TOL and len(pooled) == speed[cfg]["p95_pooled_n"])

    gold, test = golden(), split_rows("test")
    for cfg in ("cascade400", "cascade500"):
        pp, sj = A2 / "accuracy" / f"{cfg}_test_predictions.csv", jload(A2 / "accuracy" / f"{cfg}_test.json")
        if pp.exists() and sj:
            rows = {r["row"]: r["predicted"] for r in read_csv(pp)}
            k = sum(rows.get(r) == gold[r]["label"] for r in test)
            chk(f"{cfg} test accuracy", f"{k}/{len(test)}", f"{sj['correct']}/{sj['n']}", k == sj["correct"])

    deck = Path(os.getenv("DECK_OUT", str(ROOT / "deck" / "Group09_A2.pptx")))
    if deck.exists():
        try:
            from pptx import Presentation
            parts = []
            for s in Presentation(deck).slides:
                for sh in s.shapes:
                    if sh.has_text_frame:
                        parts.append(sh.text_frame.text)
                    if getattr(sh, "has_table", False) and sh.has_table:
                        parts += [cell.text for row in sh.table.rows for cell in row.cells]
            words = " ".join(parts)
            n = len(Presentation(deck).slides)
            chk("deck: slides / PENDING / DRAFT", deck.name, f"{n} slides, PENDING {'present' if 'PENDING' in words else 'none'}, "
                f"DRAFT {'present' if 'DRAFT' in words else 'none'}", n <= 8 and "PENDING" not in words and "DRAFT" not in words)
        except ImportError:
            lines.append("| deck | python-pptx not installed | | skipped |")

    lines += ["", "**All figures reconcile with the raw files.**" if not bad else f"**{bad} mismatch(es): fix before submitting.**"]
    (A2 / "crosscheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
