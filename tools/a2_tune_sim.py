#!/usr/bin/env python3
"""Assignment 2, Step 2: choose the escalation rule on the TUNING set only.

Replays every candidate rule over the Assignment 1 prediction records of the
88 tuning tickets. Models run at temperature 0 with a fixed seed, so a model's
answer to a ticket in a cascade is its Assignment 1 answer; latency per ticket
is the Assignment 1 single-request server latency (sequential, no load).

For each rule it reports accuracy (overall, per category, against the tuning
set's own reference: 7b's tuning score - 10 / - 15 points), the escalation
fraction and the mean modelled latency per ticket:
    small-model latency (if the small model is called)
  + large-model latency (if the ticket reaches the large model)

Test rows are never read. The script asserts this.

    python3 tools/a2_tune_sim.py      -> docs/a2/tuning_analysis.md, docs/a2/tuning_analysis.json
"""
from __future__ import annotations

import itertools
import statistics as st

from a2_common import (CATS, DOCS_A2, MODELS, SHORT, TOP_MODEL, UNPARSED, a1_predictions, golden, jdump,
                       split_rows)

TUNE = split_rows("tune")
TEST = set(split_rows("test"))
assert not TEST & set(TUNE)
G = golden()
P = {m: {r: v for r, v in a1_predictions(m).items() if r in set(TUNE)} for m in MODELS}  # tuning rows ONLY
LARGE = TOP_MODEL
SMALLS = ["llama3.2:3b", "llama3.2:1b", "qwen2.5:0.5b"]
CUTS = [300, 400, 450, 500, 550, 600, 700, 800, 1000]


def nchars(r):
    return len(G[r]["narrative"])


def lat(m, r):
    return float(P[m][r]["server_latency_ms"]) / 1000


def run(rule):
    """rule(r) -> (final_model, small_called: bool). Returns metrics dict."""
    pred, t, esc = {}, [], 0
    for r in TUNE:
        final, small_called, small = rule(r)
        ms = (lat(small, r) if small_called else 0) + (lat(LARGE, r) if final == LARGE else 0)
        t.append(ms)
        esc += final == LARGE
        pred[r] = P[final][r]["predicted"]
    ok = sum(pred[r] == G[r]["label"] for r in TUNE)
    per = {c: (sum(pred[r] == c for r in TUNE if G[r]["label"] == c), sum(G[r]["label"] == c for r in TUNE)) for c in CATS}
    return {"correct": ok, "n": len(TUNE), "acc": ok / len(TUNE), "escalated": esc, "esc_frac": esc / len(TUNE),
            "mean_s": st.mean(t), "median_s": st.median(t), "per_category": per}


def length_rule(small, cut):
    def f(r):
        if nchars(r) > cut:
            return LARGE, False, small
        return (small if P[small][r]["predicted"] != UNPARSED else LARGE), True, small
    return f


def category_rule(small, accept):
    def f(r):
        return (small if P[small][r]["predicted"] in accept else LARGE), True, small
    return f


def main() -> int:
    ref = run(lambda r: (LARGE, False, None))
    ref_cat = {c: k / n for c, (k, n) in ref["per_category"].items()}
    ov_lim = ref["acc"] - 0.10

    def verdict(m):
        worst = min(((k / n - ref_cat[c]) * 100, c) for c, (k, n) in m["per_category"].items())
        m["worst_gap_pts"], m["worst_cat"] = worst
        m["passes_tune"] = m["acc"] >= ov_lim - 1e-9 and worst[0] >= -15 - 1e-9
        m["faster_than_large"] = m["mean_s"] < ref["mean_s"]
        return m

    out = {"reference": ref, "families": {}}
    lines = ["# Tuning-set analysis (Step 2)", "",
             "Generated by `tools/a2_tune_sim.py` from the Assignment 1 prediction records of the **88 tuning tickets only**",
             "(`golden/a2_split.csv`, set = tune). Test rows are never read. Latency is the Assignment 1 sequential",
             "single-request server latency, so these are *no-load* estimates used to choose a rule, not results.", "",
             f"Reference, `{LARGE}` alone on the tuning set: **{ref['correct']}/88 = {ref['acc']*100:.1f} %**, mean "
             f"{ref['mean_s']:.1f} s per ticket. Tuning-set check used below: overall ≥ {ov_lim*100:.1f} % and no category "
             "more than 15 points below 7b's tuning-set category score.", ""]

    # 1. Single small models (sanity: why a cascade is needed at all)
    lines += ["## 1. Small models alone", "", "| Model | Correct | Accuracy | Mean latency (s) | Mean as % of 7b |", "|---|---|---|---|---|"]
    for s in SMALLS:
        m = run(lambda r, s=s: (s, True, s))
        lines.append(f"| `{s}` | {m['correct']}/88 | {m['acc']*100:.1f} % | {m['mean_s']:.1f} | {m['mean_s']/ref['mean_s']*100:.0f} % |")
    lines.append("")

    # 2. Where does length predict small-model errors?
    lines += ["## 2. Does ticket length predict where the small model is wrong?", "",
              "| Narrative length (chars) | Tickets | 3b correct | 7b correct | 3b mean s | 7b mean s |", "|---|---|---|---|---|---|"]
    buckets = [(0, 300), (300, 400), (400, 500), (500, 700), (700, 1000), (1000, 1500), (1500, 99999)]
    bk = []
    for lo, hi in buckets:
        rs = [r for r in TUNE if lo < nchars(r) <= hi]
        a = sum(P["llama3.2:3b"][r]["correct"] == "1" for r in rs)
        b = sum(P[LARGE][r]["correct"] == "1" for r in rs)
        bk.append({"lo": lo, "hi": hi, "n": len(rs), "3b": a, "7b": b})
        lines.append(f"| {lo+1}–{hi if hi < 99999 else 'max'} | {len(rs)} | {a} | {b} | "
                     f"{st.mean(lat('llama3.2:3b', r) for r in rs):.1f} | {st.mean(lat(LARGE, r) for r in rs):.1f} |")
    short = [r for r in TUNE if nchars(r) <= 500]
    long_ = [r for r in TUNE if nchars(r) > 500]
    f3 = lambda rs: sum(P["llama3.2:3b"][r]["correct"] == "1" for r in rs)
    f7 = lambda rs: sum(P[LARGE][r]["correct"] == "1" for r in rs)
    lines += ["", f"≤ 500 chars: 3b {f3(short)}/{len(short)}, 7b {f7(short)}/{len(short)}. "
              f"> 500 chars: 3b {f3(long_)}/{len(long_)}, 7b {f7(long_)}/{len(long_)}. "
              "On short tickets the 3b model is about as accurate as the 7b; the gap opens on long ones.", ""]
    out["length_buckets"] = bk

    # 3. Rule families
    fam = {}
    lines += ["## 3. Candidate rules", "",
              "Mean = modelled mean latency per ticket (s). Esc = tickets whose final answer comes from 7b.", "",
              "| Rule | Small | Setting | Correct | Esc | Mean s | vs 7b | Worst category gap | Passes tune | Faster |",
              "|---|---|---|---|---|---|---|---|---|---|"]

    def row(name, small, setting, m):
        lines.append(f"| {name} | `{small}` | {setting} | {m['correct']}/88 ({m['acc']*100:.1f} %) | {m['escalated']} "
                     f"({m['esc_frac']*100:.0f} %) | {m['mean_s']:.1f} | {(m['mean_s']/ref['mean_s']-1)*100:+.0f} % | "
                     f"{m['worst_gap_pts']:+.0f} ({SHORT[m['worst_cat']]}) | {'yes' if m['passes_tune'] else 'no'} | "
                     f"{'yes' if m['faster_than_large'] else 'no'} |")

    # 3a category-based: best accept set per small model (fastest that passes; else most accurate)
    for s in SMALLS:
        cands = []
        for k in range(0, 8):
            for acc in itertools.combinations(CATS, k):
                m = verdict(run(category_rule(s, set(acc))))
                m["accept"] = list(acc)
                cands.append(m)
        passing = [m for m in cands if m["passes_tune"]]
        best = min(passing, key=lambda m: m["mean_s"]) if passing else max(cands, key=lambda m: m["acc"])
        fam.setdefault("category", {})[s] = best
        row("Category (accept set)", s, "accept " + (", ".join(SHORT[c] for c in best["accept"]) or "none")
            + ("" if passing else " — best accuracy, none pass"), best)
    # 3b length-based
    for s in SMALLS:
        for cut in CUTS:
            m = verdict(run(length_rule(s, cut)))
            fam.setdefault("length", {}).setdefault(s, {})[cut] = m
            row("Length", s, f"≤ {cut} chars → small", m)
    lines.append("")

    # 4. Slip-through for the length rule with 3b
    lines += ["## 4. Accepted small-model answers that are wrong (length rule, 3b)", "",
              "| Cut-off | Accepted | Wrong among accepted | 7b would have been right on those |", "|---|---|---|---|"]
    for cut in (400, 500):
        acc = [r for r in TUNE if nchars(r) <= cut and P["llama3.2:3b"][r]["predicted"] != UNPARSED]
        wrong = [r for r in acc if P["llama3.2:3b"][r]["correct"] != "1"]
        rescued = [r for r in wrong if P[LARGE][r]["correct"] == "1"]
        lines.append(f"| {cut} | {len(acc)} | {len(wrong)} | {len(rescued)} |")
    lines.append("")

    # Agreement: 0.5b vs 1b agreement rate (both nearly constant answers)
    agree = sum(P["qwen2.5:0.5b"][r]["predicted"] == P["llama3.2:1b"][r]["predicted"] for r in TUNE)
    top05 = max(set(P["qwen2.5:0.5b"][r]["predicted"] for r in TUNE), key=lambda c: sum(P["qwen2.5:0.5b"][r]["predicted"] == c for r in TUNE))
    top1 = max(set(P["llama3.2:1b"][r]["predicted"] for r in TUNE), key=lambda c: sum(P["llama3.2:1b"][r]["predicted"] == c for r in TUNE))
    n05 = sum(P["qwen2.5:0.5b"][r]["predicted"] == top05 for r in TUNE)
    n1 = sum(P["llama3.2:1b"][r]["predicted"] == top1 for r in TUNE)
    lines += ["## 5. Rules not taken further", "",
              f"* **Agreement (0.5b + 1b):** the two models agree on {agree}/88 tuning tickets; 0.5b answers `{top05}` "
              f"for {n05}/88 and 1b answers `{top1}` for {n1}/88, so disagreement says nothing about whether either is right. "
              "A 3b pair partner would cost two 3b calls (~2 × 47 % of a 7b call) before any escalation.",
              "* **Self-reported confidence:** needs a second prompt and so a second call on every ticket; small models that "
              "answer the same category for most tickets (above) give no reason to expect calibrated confidence.",
              "* **Category-based:** the 3b model puts 50/88 tuning tickets into `Bank account or service` (11 right). "
              "Escalating those means ≥ 57 % escalation on top of a 3b call that already costs ~47 % of a 7b call, "
              "so it is slower than 7b alone even before queueing (table above).", ""]

    chosen = {"small": "llama3.2:3b", "large": LARGE, "settings": [400, 500]}
    out["families"] = {"category": {s: {k: v for k, v in m.items() if k != "per_category"} | {"per_category": m["per_category"]}
                                    for s, m in fam["category"].items()},
                       "length": {s: {str(c): m for c, m in d.items()} for s, d in fam["length"].items()}}
    out["chosen"] = chosen
    m4, m5 = fam["length"]["llama3.2:3b"][400], fam["length"]["llama3.2:3b"][500]
    lines += ["## 6. Choice", "",
              "**Length rule, `llama3.2:3b` → `qwen2.5:7b`, two settings: cut-off 400 and 500 characters.**", "",
              f"* 500 chars is the largest cut-off that passes the tuning-set check: {m5['correct']}/88, worst category "
              f"{m5['worst_gap_pts']:+.0f} points ({m5['worst_cat']}), modelled mean {m5['mean_s']:.1f} s vs "
              f"{ref['mean_s']:.1f} s for 7b ({(m5['mean_s']/ref['mean_s']-1)*100:+.0f} %). 550 already fails Credit reporting.",
              f"* 400 chars is the conservative setting: {m4['correct']}/88, worst category {m4['worst_gap_pts']:+.0f} points, "
              f"modelled mean {m4['mean_s']:.1f} s ({(m4['mean_s']/ref['mean_s']-1)*100:+.0f} %). It keeps 5 points of headroom "
              "on the binding category for the test set.",
              "* Every rule with 1b or 0.5b as the small model fails the tuning check at any setting that saves time, and "
              "no category rule is faster than 7b alone. The 3b length rule is the only family that is both inside the limits "
              "and faster on the tuning set — and only by a few percent at no load, so the speed test decides.", ""]
    for s in SMALLS:
        for cut, m in fam["length"][s].items():
            m.pop("per_category_detail", None)
    jdump(DOCS_A2 / "tuning_analysis.json", out)
    (DOCS_A2 / "tuning_analysis.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
