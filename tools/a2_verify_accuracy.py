#!/usr/bin/env python3
"""Independent check of the cascade accuracy files (the hand check in the team guide, automated).

For each cascade setting it re-derives everything from the per-ticket file and
the golden set, not from the summary JSON, then compares:
  * correct counts per category and overall    (predictions.csv vs <config>_test.json)
  * every ticket is in the service log and has a final model
  * escalated == (chars > T) or the route says "unparsed"   (the rule was applied)
  * pass / fail against docs/a2/limits.json, with the margin in tickets
  * categories that lost or gained tickets against qwen2.5:7b alone, and what the
    small model answered on the tickets it got wrong

    python3 tools/a2_verify_accuracy.py      -> docs/a2/accuracy_notes.md   (exit 1 on any mismatch)
"""
from __future__ import annotations

import sys
from collections import Counter

from a2_common import A2, CATS, DOCS_A2, DOCS_OUT, SHORT, golden, jload, read_csv, split_rows

CASCADES = {"cascade400": 400, "cascade500": 500}


def main() -> int:
    gold = golden()
    test = split_rows("test")
    limits = jload(DOCS_A2 / "limits.json")
    top = jload(A2 / "accuracy" / "single_qwen2.5_7b_test.json")
    lines = ["# Accuracy check notes (generated by `tools/a2_verify_accuracy.py`)", "",
             "Re-derived from the per-ticket files and the golden set, independently of the summary JSON.", ""]
    problems = 0
    for cfg, T in CASCADES.items():
        pj = A2 / "accuracy" / f"{cfg}_test_predictions.csv"
        sj = jload(A2 / "accuracy" / f"{cfg}_test.json")
        if not pj.exists() or not sj:
            lines += [f"## {cfg}", "", "Not measured yet.", ""]
            continue
        rows = {r["row"]: r for r in read_csv(pj)}
        issues = []
        if sorted(rows) != sorted(test):
            issues.append(f"rows differ from the test set ({len(rows)} vs {len(test)})")
        ok = sum(rows[r]["predicted"] == gold[r]["label"] for r in test if r in rows)
        if ok != sj["correct"]:
            issues.append(f"overall correct {ok} by hand vs {sj['correct']} in the JSON")
        cat_lines = []
        for c in CATS:
            rs = [r for r in test if gold[r]["label"] == c and r in rows]
            k = sum(rows[r]["predicted"] == c for r in rs)
            if k != sj["per_category"][c]["correct"]:
                issues.append(f"{c}: {k} by hand vs {sj['per_category'][c]['correct']} in the JSON")
            lim = limits["category_min_correct"][c]
            t7 = top["per_category"][c]["correct"]
            mark = "pass" if k >= lim else "**FAIL**"
            cat_lines.append(f"| {c} | {k}/{len(rs)} | {t7}/{len(rs)} | {k - t7:+d} | ≥ {lim} | {mark} ({k - lim:+d} tickets) |")
        missing = [r for r in rows.values() if r.get("in_log") != "True" or not r.get("final_model")]
        if missing:
            issues.append(f"{len(missing)} ticket(s) missing from the service log or without final_model")
        wrong_rule = []
        for r in rows.values():
            esc = r.get("escalated") == "True"
            want = int(r["chars"]) > T or "unparsed" in (r.get("route") or "")
            if esc != want:
                wrong_rule.append(r["row"])
        if wrong_rule:
            issues.append(f"escalation does not follow the rule on rows {', '.join(wrong_rule)}")
        problems += len(issues)

        kept = [r for r in rows.values() if r.get("escalated") == "False"]
        kept_wrong = [r for r in kept if r["predicted"] != gold[r["row"]]["label"]]
        answered = Counter(r["predicted"] for r in kept_wrong)
        lost = [c for c in CATS if sj["per_category"][c]["correct"] < top["per_category"][c]["correct"]]
        lines += [f"## {cfg} (T = {T})", "",
                  f"Overall {ok}/{len(test)} by hand, {sj['correct']}/{len(test)} in the JSON; limit ≥ {limits['overall_min_correct']} "
                  f"→ {'pass' if ok >= limits['overall_min_correct'] else '**FAIL**'} ({ok - limits['overall_min_correct']:+d} tickets).", "",
                  "| Category | Cascade | 7b alone | Δ | Limit | Verdict |", "|---|---|---|---|---|---|", *cat_lines, "",
                  f"Kept the small model's answer on {len(kept)} tickets; {len(kept_wrong)} of those were wrong"
                  + (f", mostly answered as {', '.join(f'{SHORT.get(k, k)} ×{v}' for k, v in answered.most_common(3))}." if kept_wrong else "."),
                  f"Categories that lost tickets against 7b alone: {', '.join(lost) or 'none'}.", "",
                  ("**Checks: all passed.**" if not issues else "**Problems:**\n" + "\n".join(f"- {i}" for i in issues)), ""]
    # Confusion matrix for every configuration (brief, Step 4: "and a confusion matrix").
    lines += ["## Confusion matrices, every configuration (test set; rows = golden, columns = predicted)", ""]
    configs = [(f"{m} alone (A1 records)", A2 / "accuracy" / f"single_{m.replace(':', '_')}_test.json")
               for m in ("qwen2.5:0.5b", "llama3.2:1b", "llama3.2:3b", "qwen2.5:7b")]
    configs += [(f"cascade T={T}", A2 / "accuracy" / f"{c}_test.json") for c, T in CASCADES.items()]
    cols = CATS + ["UNPARSED"]
    for name, path in configs:
        j = jload(path)
        if not j:
            lines += [f"**{name}:** not measured.", ""]
            continue
        lines += [f"**{name}:** {j['correct']}/{j['n']}", "",
                  "| golden \\ predicted | " + " | ".join(SHORT.get(c, "UNP") for c in cols) + " |",
                  "|---|" + "---|" * len(cols)]
        for g in CATS:
            lines.append(f"| {SHORT[g]} | " + " | ".join(str(j["confusion"][g].get(c, 0) or "") for c in cols) + " |")
        lines.append("")
    (DOCS_OUT / "accuracy_notes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
