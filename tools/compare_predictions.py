#!/usr/bin/env python3
"""Frozen prediction record vs measured outcomes -> docs/prediction_outcomes.md

Parses the numbers straight out of docs/prediction_record.md (so the frozen file
stays the single source) and compares them with results/accuracy/summary_*.json,
results/jtl/*_summary.json and results/stress/*.summary.json. Slide 11 uses the
output; the account of WHY each WRONG row was wrong is written by M5.

    python3 tools/compare_predictions.py
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"


def num(s):
    s = s.replace("*", "").replace(",", "").replace("%", "").strip()
    m = re.search(r"[\d.]+", s)
    return float(m.group()) if m else None


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    rec = (ROOT / "docs" / "prediction_record.md").read_text(encoding="utf-8")
    preds = {}
    for line in rec.splitlines():
        m = re.match(r"\|\s*`([^`]+)`\s*\|\s*[\d.]+B\s*\|(.+?)\|(.+?)\|(.+?)\|", line)
        if m:
            preds[m[1]] = {"acc": num(m[2]) / 100, "p50": num(m[3]), "p95": num(m[4])}
    stress_pred = re.search(r"max sustainable rate:\*\*\s*\*\*([\d.]+) tickets/min\s*±\s*(\d+)\s*%", rec)
    confusion_pred = re.search(r"\*\*golden (.+?) → predicted (.+?)\*\*", rec)
    hardest = re.findall(r"\|\s*\d(?: \((?:hardest|easiest)\))?\s*\|\s*([A-Za-z ]+?)\s*\|", rec)
    rows = []

    def add(claim, p, m, ok):
        rows.append((claim, p, m, "RIGHT" if ok else "WRONG"))

    measured = {}
    for model, p in preds.items():
        safe = model.replace(":", "_").replace("/", "_")
        sp = RES / "accuracy" / f"summary_{safe}.json"
        if not sp.exists():
            continue
        a = json.loads(sp.read_text(encoding="utf-8"))
        measured[model] = a
        acc = a["overall_accuracy"]
        add(f"{model} accuracy", f"{p['acc']:.0%}", f"{acc:.1%}", abs(acc - p["acc"]) <= 0.05)
        lat = a["latency_ms"]
        add(f"{model} single p50", f"{p['p50']:.0f} ms", f"{lat['p50']:.0f} ms", abs(lat["p50"] - p["p50"]) <= 0.3 * p["p50"])
        add(f"{model} single p95", f"{p['p95']:.0f} ms", f"{lat['p95']:.0f} ms", abs(lat["p95"] - p["p95"]) <= 0.3 * p["p95"])
    if len(measured) >= 2:
        by_size = list(measured)
        by_acc = sorted(measured, key=lambda m: measured[m]["overall_accuracy"])
        add("accuracy rises with size", " < ".join(by_size), " < ".join(by_acc), by_size == by_acc)
        any85 = any(a["overall_accuracy"] >= 0.85 for a in measured.values())
        add("any model meets R4 (85 %)", "no", "yes" if any85 else "no", not any85)
        recall = Counter()
        for a in measured.values():
            for c, v in a["per_category"].items():
                recall[c] += (v["recall"] or 0) / len(measured)
        ranked = [c for c, _ in sorted(recall.items(), key=lambda kv: kv[1])]
        if hardest:
            add("hardest category", hardest[0], f"{ranked[0]} ({recall[ranked[0]]:.0%} mean recall)", ranked[0] == hardest[0])
            add("easiest category", hardest[-1], f"{ranked[-1]} ({recall[ranked[-1]]:.0%})", ranked[-1] == hardest[-1])
        if confusion_pred:
            g, pr = confusion_pred[1].strip(), confusion_pred[2].strip()
            tops = {}
            for m, a in measured.items():
                cm = a["confusion_matrix"]
                cells = [(cm[gg][pp], gg, pp) for gg in cm for pp in cm[gg] if gg != pp]
                n, gg, pp = max(cells)
                tops[m] = f"{gg} → {pp} ({n})"
            add("largest confusion", f"{g} → {pr}", "; ".join(f"{m}: {t}" for m, t in tops.items()),
                all(t.startswith(f"{g} → {pr}") for t in tops.values()))
    for p in sorted((RES / "stress").glob("*.summary.json")):
        s = json.loads(p.read_text())
        if stress_pred and "3b" in s["model"]:
            want, tol = float(stress_pred[1]), float(stress_pred[2]) / 100
            got = s["max_sustainable_per_min"]
            add(f"stress limit {s['model']} ({s.get('run') or p.name.split('.summary')[0]})", f"{want:g}/min ±{tol:.0%}",
                f"{'none sustained' if got is None else f'{got:g}/min'} (saturated {s['saturated_throughput_per_min']}/min, errors {s['total_errors']})",
                got is not None and abs(got - want) <= tol * want)
    lines = ["# Predictions vs outcomes (generated by tools/compare_predictions.py)", "",
             "| Claim | Predicted | Measured | Verdict |", "|---|---|---|---|"]
    lines += [f"| {c} | {p} | {m} | {v} |" for c, p, m, v in rows]
    lines += ["", "Tolerances: accuracy ±5 points; latency ±30 %; stress limit as stated in the record.",
              "For every WRONG row, M5 writes why the mental model was off in docs/prediction_account.md."]
    (ROOT / "docs" / "prediction_outcomes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
